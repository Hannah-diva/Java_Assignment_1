package session3;

public class C2_For_Loop {
    public static void main(String[] args) {

        // For loop

        // Even numbers from 2 to 20
        for (int i = 2; i<=20  ; i+=2) {
            System.out.println("number : " + i);
        }

        // Descending order from 20 to 0
        for ( int i = 20 ; i>=0 ; i-- ) {
            System.out.println(i);
        }



    }

}
